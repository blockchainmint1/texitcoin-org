  $$There is a sentence every honest person should be able to say:

**I got it wrong.**

That sentence is not weakness. It is not surrender. It is not humiliation. It is how trust survives contact with reality.

We all make mistakes. Every day gives us another chance to do better. It is never too late to say sorry, correct the record, and stop damage that never should have continued.

That is true in crypto. It is true in business. It is true in ordinary life. And it must be especially true in government, where a mistake is backed by the power of the state and the consequences land on real people.

For weeks after the August hearing in **TSSB v. TEXITcoin**, we said relatively little about what happened next. This is the first part of that story.

The short version is simple: after four days of testimony, our attorneys gave the Texas State Securities Board a clear opportunity to withdraw its Emergency Cease and Desist Order, dismiss the case, and correct claims they argued the hearing record had shown to be false. The TSSB declined. It chose to continue the process and defend the order in post-hearing briefing.

No judge has issued a final decision. This article is our account and our opinion, grounded in the hearing, our attorneys’ August 28 letter, and the TSSB’s written response. The official record controls. But an undecided case does not require us to pretend that nothing important happened in that hearing room.

## Before the hearing, uncertainty was understandable

I want to begin with grace, because grace matters.

When the TSSB issued its emergency order in February, its people did not yet know everything we knew. They had conducted an undercover investigation. They had watched calls, gathered materials, interviewed people, and reached conclusions we believed were catastrophically wrong. But I could still understand the starting point: regulators are supposed to investigate suspicious activity, and crypto has given them plenty of genuine scams to investigate.

We know this industry. We know what fraud looks like. We know why skeptical regulators exist.

The TSSB could have believed it was protecting the public. It could have misunderstood a mining package, mistaken a service contract for an investment contract, or confused confidence in a currency project with a guarantee of profit. It could have looked at a complicated, unconventional business and gotten the facts wrong.

People get things wrong.

The real test of integrity is what happens after the facts change.

## I gave them the off-ramp in the hearing room

I was the first witness called by the TSSB in its case. I spent hours answering its questions before our lawyers presented our side.

At the end of my testimony, I made an appeal that had very little to do with legal gamesmanship. My point was this: maybe the Board could claim it did not know the truth when it issued the order. It knew much more now.

As I later recalled during our [post-hearing Honest Money call](https://texitcoin.org/zoom/2026-08-20-tssb-vs-texitcoin-rewind), I told the room that the TSSB’s leadership still had the power to stop and correct the record. The commissioner could stand up, acknowledge that material statements in the order were wrong, and keep the case from collapsing under claims that should never have remained in it.

That recollection is not an official transcript, and readers should treat it accordingly. But the principle is the important part: **we gave the agency an off-ramp in public, before the hearing was even over.**

Nobody took it.

## Then the investigator testified

The most serious problem was not simply that we disagreed with the TSSB’s interpretation of securities law. Reasonable lawyers can disagree about new technology. The deeper problem, according to our attorneys’ post-hearing letter, was what the Board’s own lead investigator acknowledged under oath.

The Emergency Order stated that purchasers “never receive any mining hardware or control over mining hardware.” Our counsel’s August 28 letter says investigator Phillip Fuselier’s testimony established there was no basis for that categorical claim.

The order also accused us of intentionally failing to disclose the Mulligan Mint bankruptcy. Our lawyers wrote that the public record showed I had disclosed it repeatedly, and that Fuselier testified he knew about those disclosures before the order was filed.

The letter identifies other concessions as well: that customers received the computational resources they were promised; that those resources produced TXC; that TXC’s value was never guaranteed; that information about personnel, security, maintenance, and mining operations had been publicly discussed; and that some named respondents were not legal entities capable of ceasing or desisting anything.

Those are not findings from the judge. They are the respondents’ description of the evidence and testimony, set out by our legal team in a formal letter demanding corrective action. The TSSB remains free to dispute that characterization in its briefs.

But this was not internet gossip. It was not a meme. It was not a Telegram argument.

It was sworn testimony in a state administrative hearing, followed by a written demand from counsel at Quinn Emanuel and Wright Close Barger & Guzman.

Mati Allin, who attended all 26.5 hours, gave a careful eyewitness account in his guest article, [“Did TEXITcoin Make Its Winning Case?”](https://texitcoin.org/blog/guest-post-mati-allin-tssb-v-texitcoin-hearing). Mati repeatedly cautioned that no one had officially won and that his notes were not an official transcript. Even with those responsible caveats, he came away believing that the fraud theory was the weakest part of the state’s case.

That distinction matters. We are not claiming a ruling that has not happened. We are saying the hearing created a record the agency had a duty to confront honestly.

## Our attorneys asked them to do the right thing

On August 28, our legal team sent the TSSB a three-page letter. It did not ask for a favor. It did not ask the Board to ignore the process. It argued that the evidence and testimony required the commissioner to withdraw the Emergency Order in full and dismiss the case with prejudice.

The letter was direct because the situation was serious.

Our lawyers wrote that the hearing had exposed deficiencies in the order’s factual and legal foundation and raised “serious concern about its ethical basis.” They cited the duty of government lawyers to correct statements learned to be untrue. They argued that maintaining allegations known or learned to be false is incompatible with the government’s obligation to pursue the truth.

The letter also addressed the consequences of pressing forward. It cited Texas provisions allowing attorney’s fees and costs for defending against a frivolous regulatory action and warned that respondents were prepared to seek findings, sanctions, fees, and other appropriate relief.

But it also left the door open. The letter said we would prefer voluntary correction. It asked the Board to withdraw by September 4.

That was another off-ramp.

## The answer: process over correction

The TSSB replied the same day.

Its response did not engage with the specific factual points raised in our letter. It did not explain why the “never receive any mining hardware” statement should remain. It did not answer the bankruptcy-disclosure issue. It did not address our counsel’s account of what its investigator admitted knowing before the order was issued.

Instead, the Board said the hearing had occurred and the statutory process allowed the Emergency Order to be affirmed, modified, or set aside. It said its Enforcement Division would address the evidence in its closing brief and ask the administrative law judge for a Proposal for Decision. It wrote:

> “We do not agree that the proper course is to withdraw the Emergency Order and dismiss the proceeding before completion of the statutory contested case process.”

And then:

> “We will proceed through the established process and address the merits in our closing brief.”

That is the answer we received.

Procedure matters. Due process matters. An orderly record matters. But process is not a moral shield against correction. A government agency does not lose the ability to do the right thing merely because a proceeding has begun. Our lawyers specifically cited the rule permitting withdrawal before post-hearing briefs and a prior TSSB matter in which an emergency order was withdrawn.

The choice was available.

They chose not to take it.

## “We will address it later” does not stop today’s damage

The Emergency Order did not disappear when the hearing ended. Its accusations continue to live online. They continue to appear in searches. They continue to be repeated by people who have never watched one minute of testimony or read one exhibit.

Each day that an allegedly false claim remains uncorrected is another day of reputational damage.

That damage is not theoretical. An accusation issued under the seal of government carries a credibility that an ordinary critic does not. People assume the government checked. They assume an “emergency” meant there was an emergency. They assume an allegation printed in an official order must rest on reliable evidence.

When the record changes, the responsibility changes too.

A regulator cannot reasonably ask the accused to wait quietly while reputational harm compounds, then treat the mere passage of time as neutral. Delay has a direction. Silence has a cost. A claim left standing continues doing work in the world.

We have been patient because we respect the process. We complied. We stopped sales globally even though the order applied to conduct in or from Texas. We hired serious counsel. We produced records. We answered questions under oath. We sat through four days of hearing. We allowed the evidence to speak.

Patience is not consent.

Grace is not permission to continue.

## Government must meet the standard it demands from everyone else

Crypto needs accountability. Bad actors deserve scrutiny. Promoters who lie, steal, conceal, or promise impossible returns should be exposed and stopped.

But accountability cannot be a one-way instrument.

We must hold one another accountable inside crypto. We must hold companies accountable in society. And above all, we must hold government accountable when it uses public authority to accuse citizens and businesses of fraud.

The standard cannot be: regulators may publish first, learn later, and leave the original accusation untouched while the accused absorbs the damage.

The standard should be the same one we teach our children and expect from our neighbors:

Tell the truth. Admit mistakes. Correct them quickly. Apologize when an apology is owed. Repair what can be repaired.

The greater the power, the greater that duty becomes.

## We are running out of cheeks to turn

We have tried to be graceful. We have tried to be patient. We have tried to respect every step of the process even when we believed the process was being used to preserve claims the evidence could not support.

There is a limit to how long “wait for the process” can substitute for “address the facts.”

We are coming close to that limit.

The TSSB has had the benefit of its investigation, our disclosures, the documents, the cross-examination, its own investigator’s testimony, four days before an administrative law judge, and a detailed post-hearing letter from our counsel. It has had more than enough time to distinguish a correctable mistake from a claim it is willing to defend with a fully developed record.

If the Board believes every material allegation remains accurate, it should explain why. If it knows some are not, it should retract them now. Not after another season of reputational harm. Not after another round of legal bills. Not hidden inside a brief that few members of the public will ever read.

Now.

It is not too late to do the right thing.

It is not too late to say: we got part of this wrong.

It is not too late to correct the public record.

But every day makes the decision clearer — and the continued silence harder to excuse.

