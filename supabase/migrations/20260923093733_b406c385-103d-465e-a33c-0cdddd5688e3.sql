  $$The Texas State Securities Board had a chance to do the right thing.

It chose not to.

After the August hearing, our attorneys laid out the testimony they believe showed that central allegations in the TSSB’s Emergency Cease and Desist Order were false—and, in several instances, that the agency’s investigator knew the underlying facts before the order was issued. We asked the Board to withdraw the order, dismiss the case, and stop the reputational damage.

The Board declined.

So on September 22, our attorneys wrote to Governor Greg Abbott.

We did not ask the Governor to decide the case. We did not ask him to bend the law for us. We asked his office to review the conduct of a state agency before that conduct is memorialized in formal findings and before the damage spreads any further.

We are confident in our case. We are not asking for help because we think TEXITcoin cannot survive without it.

We are asking because intervention is the right thing to do—and because someone in Texas government has to be willing to do it.

## This is no longer just about us

The letter begins with the stakes plainly stated: our lawyers believe this enforcement action threatens the fast-growing digital-asset mining industry in Texas.

The TSSB’s core theory is that our mining packages involved securities transactions. If that theory prevails in the form the agency has pursued it, the implications do not stop at TEXITcoin. The same logic could reach other Texas businesses that provide infrastructure allowing customers to participate in digital mining without installing an industrial operation in their homes.

That matters in a state that has worked hard to call itself friendly to Bitcoin, blockchain, energy innovation, and entrepreneurs.

Texas established a strategic Bitcoin reserve. National policy has moved toward recognizing the importance of digital assets. Federal regulators have expressly said that certain proof-of-work mining activities do not involve offers and sales of securities under federal law.

Federal guidance does not decide a Texas securities case, and we are not pretending it does. But it makes the policy contradiction impossible to ignore: while elected leaders tell the world that Texas wants to help lead the digital-asset economy, one state agency is advancing a theory our counsel calls unprecedented—one that could make builders and investors wonder whether Texas is actually open for this business.

A state cannot credibly court an industry with one hand while an agency threatens its basic operating model with the other.

## The record the Governor was asked to review

Our September 22 letter gives Governor Abbott’s office a detailed account of what our attorneys say happened under oath.

The most direct example concerns this statement in the Emergency Order:

> “Investors never receive any mining hardware or control over mining hardware.”

According to the hearing transcript excerpt included in our letter, the TSSB’s lead investigator, Phillip Fuselier, ultimately acknowledged that statement was false:

> **Q.** You now know that allegation is false?  
> **A.** Correct.  
> **Q.** Because some purchasers did get at-home mining equipment?  
> **A.** Yes.

The letter identifies several other exchanges.

The order alleged that I intentionally failed to disclose the bankruptcy of Mulligan Mint, a company I owned more than a decade ago. In the transcript excerpt cited by our attorneys, the investigator acknowledged that he had seen evidence of my public statements about that bankruptcy before the cease-and-desist order was filed—and that the order nevertheless alleged intentional concealment.

The order alleged failures to disclose information about mining operations, equipment failures, power outages, network interruptions, and site security. The cited testimony says the investigator knew before the order was filed that those matters had been discussed publicly on our Zoom calls.

The order raised paper checks payable to Danager Resources. The cited testimony says the investigator did not interview anyone who had actually paid that way.

These excerpts are presented by our lawyers in an advocacy letter. The administrative law judge has not yet issued a final decision, and the complete official record—not our article—controls. But the words quoted from the hearing are not vague impressions. They are specific questions and answers with transcript citations.

The Governor’s office can review them for itself.

## The TSSB was already given a chance to correct this

This is not our first request for restraint.

On August 28, our attorneys wrote directly to the TSSB and asked it to withdraw the Emergency Order and dismiss the proceeding with prejudice. That letter argued that the hearing had exposed severe problems in the order’s factual and legal foundation. It also warned that continuing to press claims our counsel believes are frivolous could support requests for sanctions, fees, and other relief.

The TSSB answered that same day. It declined to withdraw the order and said it would proceed through the established contested-case process.

We discussed that decision in [“The Off-Ramp Was Right There”](https://texitcoin.org/blog/the-off-ramp-was-right-there-tssb-after-the-hearing?preview=txc-draft-preview). The agency had an opportunity to address the substance and stop the ongoing harm. Instead, it pointed to procedure and kept moving.

Procedure matters. It does not excuse a government body from correcting claims when the evidence changes—or, as our counsel contends here, when its own witness confirms that the agency possessed contrary information from the beginning.

## There is a history the Governor should examine

The letter also asks the Governor to view this case in a wider context.

Our attorneys point to two other recent TSSB crypto enforcement matters. In the Billionico Academy case, they write, an administrative law judge found that the agency had not established jurisdiction over any of the nine respondents who challenged the order, and the order was dismissed as to them. In the Apertum Holdings matter, they write, the TSSB withdrew its cease-and-desist order after its jurisdiction was challenged.

Those are separate cases with their own records. They do not decide ours. But they are relevant to a basic question: is this an isolated mistake, or is an enforcement pattern pushing beyond the agency’s mandate?

The most troubling context comes from an internal June 2025 TSSB report attached to the Governor letter.

That report concerned complaints about former Enforcement Director Joe Rotunda. It documented staff allegations of a toxic and hostile workplace and said employees reported being told that agency leadership “only want[ed] to see crypto orders,” even at the expense of other statutory responsibilities. The report also said the former director made statements about the views of agency leadership and the Governor’s office that the deputy commissioner and securities commissioner believed were false.

That internal report is not a ruling about TEXITcoin. It does not by itself prove why any particular action was taken against us. But it is an official agency document describing serious internal concerns about the enforcement division and its focus on crypto. Our attorneys argue that the conduct in our case appears to be a holdover from that era.

That argument deserves independent review—not dismissal, not spin, and not another reflexive defense of the institution.

## Why we went to the Governor

A governor does not need to micromanage every dispute involving a state agency. That is not what we are asking for.

But when an agency’s conduct threatens a major Texas industry, contradicts the state’s stated economic direction, and raises documented concerns about whether official accusations were supported by facts known to the agency, oversight is not interference. Oversight is the job.

Our attorneys’ request is targeted and urgent: review the TSSB’s conduct before formal findings of fact and conclusions of law are entered.

The letter explains why timing matters. Every day the Emergency Order remains public, its accusations keep circulating. Potential partners see it. Search engines preserve it. Critics repeat it. People who never watched the hearing understandably assume that an emergency order from a state regulator must rest on proven facts.

We expect to win on the merits. But a later victory does not automatically undo months or years of harm inflicted by allegations that should have been corrected sooner.

Governor Abbott has an opportunity to show crypto builders everywhere what Texas actually means when it says it is open for business.

Not by giving TEXITcoin special treatment.

By insisting that a Texas agency tell the truth, correct the record when necessary, and remain inside the boundaries of its authority.

## We would rather resolve this responsibly than fight it publicly

Our lawyers wrote that I am loath to raise these issues in a public forum. That is accurate.

We did not want this to become a media campaign. We did not want to turn every disputed line of an enforcement order into a press event. We tried to resolve the matter informally. We made the record at the hearing. We gave the TSSB a direct opportunity to withdraw. We then asked the Governor’s office to review the situation.

But patience cannot become permanent silence.

If the agency continues to refuse correction and meaningful oversight does not arrive, we will have very few cards left to play. One is to take the full record to the press and let the public examine the TSSB’s conduct line by line. Another is to seek every remedy Texas law provides for what our counsel characterizes as a frivolous regulatory action, including sanctions, fees, and damages where available.

We do not want escalation for its own sake. We want the false claims corrected. We want the order withdrawn. We want this state to remain a place where lawful crypto businesses can build without wondering whether an enforcement theory will be invented first and defended after its factual foundation collapses.

But if this becomes a public fight, it will be because private restraint, sworn testimony, formal legal demands, and a direct appeal for oversight were not enough.

## And if Texas eventually writes us a check?

Here is the part that may surprise people.

If we prevail and Texas is ultimately ordered to reimburse fees, pay damages, or provide other monetary relief, we do not intend to cash the check.

That money would not come from the officials who made the decisions. It would come from Texans—the same people we are trying to empower with honest money and economic independence.

We are not fighting to transfer public money into our pocket. We are fighting to stop public power from being misused and to establish that agencies can be held accountable when they pursue unsupported claims.

The principle is worth more than the check.

## Governor Abbott, the door is still open

This can still end the right way.

The Governor’s office can review the testimony, the order, the internal agency report, our August 28 demand, and the TSSB’s response. It can ask whether this case reflects Texas policy, Texas values, and the standard of integrity Texans should expect from their government.

The TSSB can still withdraw claims it cannot defend. It can still correct the record. It can still prevent more unnecessary harm to TEXITcoin and more uncertainty for the Texas crypto industry.

We hope cooler heads prevail.

Not because we need someone to rescue us.

Because doing the right thing should not require a court order.

And if it does—if we receive the verdict we expect and Texas is ready for a governor who understands honest money, government accountability, and the difference between protecting citizens and protecting bureaucracies—well...

**Maybe that will be the day we announce our candidacy for Governor of Texas.**

Stay tuned.

